function assertMapped(map, value, field) {
  if (value == null) return value;
  if (!Object.prototype.hasOwnProperty.call(map, value)) {
    throw new Error(`Missing English translation for ${field}: ${value}`);
  }
  return map[value];
}

function translateNutritionText(value) {
  if (value == null) return value;
  return value
    .replace(/\bper 100g\b/gi, 'per 100 g')
    .replace(/\bper 100ml\b/gi, 'per 100 ml')
    .replace(/\bei(wit)?\b/gi, 'protein')
    .replace(/\bkoolhydraten\b/gi, 'carbohydrates')
    .replace(/\bvezels\b/gi, 'fibre')
    .replace(/\bsuiker(s)?\b/gi, 'sugars')
    .replace(/\bvet\b/gi, 'fat')
    .replace(/\bzout\b/gi, 'salt');
}

function translatePackageDisplay(value) {
  if (value == null) return value;
  return value
    .replace(/\b(\d+(?:[.,]\d+)?)\s*kg\b/gi, '$1 kg')
    .replace(/\b(\d+(?:[.,]\d+)?)\s*g\b/gi, '$1 g')
    .replace(/\b(\d+(?:[.,]\d+)?)\s*ml\b/gi, '$1 ml')
    .replace(/\b(\d+(?:[.,]\d+)?)\s*l\b/gi, '$1 L')
    .replace(/\bGR\b/gi, 'g')
    .replace(/\bgram\b/gi, 'g')
    .replace(/\bstuks\b/gi, 'items')
    .replace(/\bstuk\b/gi, 'item')
    .replace(/\s+x\s+/gi, ' × ');
}

function translateProduct(product) {
  const name = assertMapped(productNames, product.sku, `product name for ${product.sku}`);
  const description = assertMapped(descriptions, product.sku, `description for ${product.sku}`);
  const translatedIngredients = product.ingredienten.map((ingredient) =>
    assertMapped(ingredients, ingredient, `ingredient for ${product.sku}`),
  );
  const translated = {
    ...product,
    product_naam: name,
    inhoud: {
      ...product.inhoud,
      eenheid: product.inhoud.eenheid === 'stuk' ? 'item' : product.inhoud.eenheid,
      weergave: translatePackageDisplay(product.inhoud.weergave),
    },
    categorie: product.categorie.map((category) =>
      assertMapped(categories, category, `category for ${product.sku}`),
    ),
    omschrijving: description,
    omschrijving_status: {
      afgeleid_uit_naam_en_ingredienten: 'derived from product name and ingredients',
      originele_dummydata: 'original dummy data',
    }[product.omschrijving_status],
    ingredienten: translatedIngredients,
    ingredienten_bron_tekst: translatedIngredients.join(', '),
    allergenen: {
      ...product.allergenen,
      bron_tekst: assertMapped(sourceAllergenText, product.allergenen.bron_tekst, 'allergen source text'),
      status: assertMapped(allergenStatuses, product.allergenen.status, 'allergen status'),
    },
    voedingswaarde: {
      ...product.voedingswaarde,
      basis: {
        per_100g: 'per 100 g',
        per_100ml: 'per 100 ml',
        per_ei: 'per egg',
      }[product.voedingswaarde.basis] || product.voedingswaarde.basis,
      bron_tekst: translateNutritionText(product.voedingswaarde.bron_tekst),
      status: 'parsed from dummy source',
    },
    bewaren: assertMapped(storageNotes, product.bewaren, 'storage note'),
    herkomst: assertMapped(countries, product.herkomst, 'country of origin'),
    status_datasets: 'dummy data; not verified online',
    foto: {
      ...product.foto,
      url: `/product-images/${product.sku}.jpg`,
      alt: `AI-generated illustrative image of ${name}; not the official packaging.`,
    },
  };

  if (translated.omschrijving_status === undefined) {
    throw new Error(`Missing English description status for ${product.sku}`);
  }

  return translated;
}

if (!fs.existsSync(sourcePath)) {
  throw new Error(`Dutch product catalog not found: ${sourcePath}`);
}

const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
if (!Array.isArray(source)) {
  throw new Error(`Expected an array of products in ${sourcePath}`);
}

const englishCatalog = source.map(translateProduct);
fs.writeFileSync(targetPath, `${JSON.stringify(englishCatalog, null, 2)}\n`, 'utf8');
console.log(`Translated ${englishCatalog.length} products to ${targetPath}`);
